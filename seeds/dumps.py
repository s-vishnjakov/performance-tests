from seeds.schema.result import SeedsResult
import os


def save_seeds_result(result: SeedsResult, scenario: str):
    """
    Saves the seeding result (SeedsResult) to a JSON file.

    :param result: The seeding result generated by the builder.
    :param scenario: The name of the load scenario for which the data is being generated.
                     Used to generate the file name (e.g., "credit_card_test").
    """
    if not os.path.exists("dumps"):
        os.mkdir("dumps")

    with open(f"./dumps/{scenario}_seeds.json", "w+", encoding="utf-8") as file:
        file.write(result.model_dump_json())


def load_seeds_results(scenario: str) -> SeedsResult:
    """
    Loads seeding results from a JSON file.

    :param scenario: Name of the load scenario whose data needs to be loaded.
    :return: The SeedsResult object restored from the file.
    """
    with open(f"./dumps/{scenario}_seeds.json", "r", encoding="utf-8") as file:
        return SeedsResult.model_validate_json(file.read())
